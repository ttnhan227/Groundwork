export type TranslationKey = keyof typeof TRANSLATIONS.en;

export function getActiveLanguage(): Language {
  const prefs = storedPreferences();
  return (prefs.language as Language) || "en";
}

export function translate(key: TranslationKey, params?: Record<string, string | number>, lang?: Language): string {
  const currentLang = lang || getActiveLanguage();
  const dict = (TRANSLATIONS as Record<string, Record<string, string>>)[currentLang] || TRANSLATIONS.en;
  let text: string = dict[key] || (TRANSLATIONS.en as Record<string, string>)[key] || key;

  if (params) {
    for (const [paramKey, paramVal] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, "g"), String(paramVal));
    }
  }

  return text;
}

export function useTranslation() {
  const [language, setLanguageState] = useState<Language>(getActiveLanguage);

  useEffect(() => {
    function handlePrefsChange(e: Event) {
      const customEvent = e as CustomEvent<UserPreferences>;
      if (customEvent.detail?.language) {
        setLanguageState(customEvent.detail.language as Language);
      } else {
        setLanguageState(getActiveLanguage());
      }
    }

    window.addEventListener(PREFERENCES_CHANGED_EVENT, handlePrefsChange);
    return () => {
      window.removeEventListener(PREFERENCES_CHANGED_EVENT, handlePrefsChange);
    };
  }, []);

  const changeLanguage = useCallback((newLang: Language) => {
    const prefs = storedPreferences();
    const updated: UserPreferences = { ...prefs, language: newLang };
    applyPreferences(updated);
    setLanguageState(newLang);
  }, []);

  const t = useCallback(
    (key: TranslationKey, params?: Record<string, string | number>) => {
      return translate(key, params, language);
    },
    [language],
  );

  return { t, language, setLanguage: changeLanguage, languageOptions: LANGUAGE_OPTIONS };
}
